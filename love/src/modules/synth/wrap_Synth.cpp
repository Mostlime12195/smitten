extern "C" int luaopen_love_synth(lua_State *L)
{
	using namespace love::smitten;

	lua_getglobal(L, "package");
	lua_getfield(L, -1, "preload");
	lua_getfield(L, -2, "loaded");
	lua_newtable(L);
	luaL_register(L, nullptr, native_functions);
	lua_setfield(L, -2, "love.synth.native");
	lua_pop(L, 1);
	for (const EngineLuaFile *f = synth_lua_h_files; f->name != nullptr; f++)
	{
		std::string chunkname = std::string("=[smitten \"") + f->path + "\"]";
		if (luaL_loadbuffer(L, (const char *) f->data, f->size, chunkname.c_str()) != 0)
			return lua_error(L);
		lua_setfield(L, -2, f->name);
	}
	lua_pop(L, 2);

	lua_getglobal(L, "require");
	lua_pushstring(L, "love.synth.sounds");
	lua_call(L, 1, 1);
	return 1;
}
